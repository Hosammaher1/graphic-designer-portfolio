// Helper functions for selecting projects
export function getFeaturedProjects(mode = 'manual', count = 3) {
  const published = projectsData.filter((p) => p.published);
  if (mode === 'manual') {
    return published
      .filter((p) => p.isFeatured)
      .sort((a, b) => (a.featuredOrder || 99) - (b.featuredOrder || 99))
      .slice(0, count);
  }
  return [...published]
    .sort((a, b) => new Date(b.publicationDate).getTime() - new Date(a.publicationDate).getTime())
    .slice(0, count);
}

export function getAllPublishedProjects() {
  return projectsData.filter((p) => p.published);
}

